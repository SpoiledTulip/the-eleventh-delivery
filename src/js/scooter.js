/* ============================================================
 * scooter.js — 🛵 外卖车（借车加速）（2026-10-07 改版）
 * ============================================================
 * 十一的最新要求：
 *   "去掉随机充电桩，保留外卖车。
 *    碰到外卖车可以加速几秒，外卖车没电了，就加速不了。"
 *
 * ------------------------------------------------------------
 * ★ 和旧版的区别（旧版=「骑上去按电量慢慢耗」）★
 * ------------------------------------------------------------
 *   旧版：碰到车 → **一直骑着** → 电量按时间慢慢扣 → 没电自动下车。
 *         路边还要刷充电桩来回电。
 *   现在：碰到车 → **借到几秒加速**（一次性、有计时）→ 时间到就没了。
 *         充电桩**整个删掉**。
 *
 *   为什么改版更干净：
 *     · 旧版要玩家理解"电量/充电桩/就近充电"三套概念，还得跑回去充电；
 *     · 新版只有一句话："碰到车 → 快几秒"，不需要解释。
 *     十一的原话也是"可以加速几秒"，本来就是**限时**的意思。
 *
 * ------------------------------------------------------------
 * ★ 设计原则（和项目其它新模块一致）★
 * ------------------------------------------------------------
 *   ① **完全复用现有引擎**：不改 physics.js、不动 CONFIG、
 *      不碰角色的 speedMultiplier —— 只是给"计算速度那一步"乘一个系数。
 *   ② **独立封装**：全部逻辑在本文件，对外只暴露 `SCOOTER.*`。
 *      game.js / render.js 各调一次，删掉本文件就能退回原版。
 *   ③ **绝不改物理参数**（红线）—— 外卖车是"玩法层"，不是"物理层"。
 *
 * ------------------------------------------------------------
 * ★ 为什么"只加速地面、不改跳跃"（十一早先定的，这次沿用）
 * ------------------------------------------------------------
 *   跳跃高度由 `JUMP_POWER`（初速度）决定，和水平速度无关。
 *   如果同时加速 + 加跳，会同时改变**两个维度**，可达性判定要整套重算，
 *   而且玩家分不清"这是车的效果还是角色本身的能力"。
 *   ⇒ 只改水平速度 = 影响"跑得快"，不影响"跳得高"，语义干净。
 *
 * ------------------------------------------------------------
 * ★ 三个必须做对的地方 ★
 * ------------------------------------------------------------
 *   ① **加速要"看得见倒计时"**：加速几秒，如果玩家不知道还剩多久，
 *      会以为"怎么突然就没了"。⇒ 骑手头顶挂一条递减的能量条 + 秒数提示。
 *   ② **没电的车要一眼看出来**：压暗 + 没有待取浮动。而且它**不能被借**。
 *   ③ **计时结束要有明确反馈**：一条淡出提示（`SCOOTER.takeExpired()`），
 *      而不是车"悄悄失效"。
 *
 * ------------------------------------------------------------
 * ★ 生成规则（和收餐人的思路一致）
 * ------------------------------------------------------------
 *   "有概率刷新"必须**按关卡固定**（用 goal.x 做 Knuth 哈希），
 *   **绝不能每帧随机** —— 否则玩家重进同一关会发现车时有时无，像 bug。
 *   用不同的种子偏移，让"有收餐人的关"和"有外卖车的关"不总是同一批。
 * ============================================================ */

const SCOOTER = (function () {

  /* ============================================================
   * 可调参数（全部集中在这里，改手感只改这一块）
   * ============================================================ */
  const CFG = {
    /* 借到车之后的水平速度倍率。
     * ⚠️ 不能太大：RUN_SPEED = 3 px/帧（= 180 px/s），
     *    乘 1.65 = 4.95 px/帧 = 297 px/s。
     *    再快会出现"冲过头刹不住"，而且**可能影响跳跃落点判定**
     *    （虽然跳跃高度没变，但水平位移变长了 → 会飞过原本要落的小平台）。
     *    1.65 是"明显更快、但仍能精确落点"的折中。 */
    SPEED_MUL: 1.65,

    /* ★ 借一次的加速时长（秒）★
     * 十一："碰到外卖车可以加速几秒"。
     * 4 秒 ≈ 按加速速度能跑 1188px ≈ 37 格 ——
     * 差不多是"跑过一整段连贯地形"的长度，明显爽但不会覆盖半张图。 */
    BOOST_SECONDS: 4,

    /* 满电的车能提供几次加速？（续航 = BOOST_SECONDS × BOOSTS_PER_BIKE）
     * ⚠️ 十一说"外卖车没电了，就加速不了" ⇒ 车是**会耗尽的**。
     *   2 次 = 8 秒总续航，和旧版的 FULL_SECONDS=8 保持一致的手感。
     *   用完变"没电"（压暗、不能再借）—— 一台车是一份**一次性资源**。 */
    BOOSTS_PER_BIKE: 2,

    /* 加速结束后的"不能马上再借"冷却（帧）。
     * ⚠️ 防止玩家站在车上反复触发（每次都给满 4 秒）。
     * 0.5 秒 ≈ 刚好够人跑开两步，不会觉得被卡。 */
    RELEND_COOL: 30,

    /* 倒计时告急的阈值（少于它开始闪红 + 提示） */
    LOW_RATIO: 0.25,

    /* 刷新概率：hash < 这个值就刷。
     * 0.5 = 约一半的关卡有外卖车。 */
    SPAWN_CHANCE: 0.5,

    /* 外卖车尺寸（像素） */
    W: 46,
    H: 30,
  };

  /* 每关的运行时数据：{ levelId: { bikes:[], chargers:[] } }
   * ⚠️ `chargers` 字段**保留为空数组**（不是删掉）——
   *    因为 render.js / 测试里有历史引用会遍历它；
   *    留一个空数组 = 老代码自然"什么都不画"，比删字段安全。 */
  let data = null;

  /* 一次性提示通道：ui.js / 提示层可以取走并显示一次
   * （十一要的"加速结束"反馈；见 takeExpired 的注释） */
  let expiredFlag = false;

  /* ============================================================
   * 稳定哈希（和 render.js 的 drawReceiver 同一套算法）
   * ------------------------------------------------------------
   * ⚠️ 两个地方用了**同一个算法但不同的种子偏移**，
   *    这样"有收餐人的关"和"有外卖车的关"不会总是同一批
   *    —— 否则玩家会以为它们是绑定的。
   * ============================================================ */
  function hash01(n) {
    let x = Math.abs(Math.floor(n)) || 0;
    x = (x * 2654435761) % 2147483647;
    return x / 2147483647;
  }

  /* ============================================================
   * 进关时生成（在 loadLevel 之后调用）
   * ------------------------------------------------------------
   * 只依赖 `lv`（关卡数据），不依赖玩家 —— 所以同一关**每次生成结果一样**。
   * ============================================================ */
  function buildForLevel(lv) {
    data = { bikes: [], chargers: [] };
    expiredFlag = false;
    if (!lv || !lv.spawns || !lv.spawns.length) return data;

    const T = (typeof LEVEL_TILE !== 'undefined') ? LEVEL_TILE : 32;
    const spawn = lv.spawns[0];

    /* ★ 外卖车：按关卡哈希决定刷不刷 ★
     * ⚠️ 位置必须**在能站的地面上**，不能刷在半空中。
     *    做法：选一列，往下找第一个可站的实心面。
     *    这比随机撒点可靠得多（随机撒点很容易刷在墙上/坑里）。
     *
     * ⚠️⚠️ 列位置**也要随关卡变化**！
     *    第一版我写死 `lv.cols * 0.35` —— 而所有关卡都是 88 列，
     *    结果 6 台车**全刷在 col31**。玩家玩到第几关都看到车在同一个位置，
     *    会明显觉得"这是复制的"（实测发现，已修）。
     *    ⇒ 现在把哈希的小数部分用在列位置上，让每关都不一样。 */
    const seedBike = hash01(spawn.x * 3 + lv.id * 977);
    if (seedBike < CFG.SPAWN_CHANCE) {
      /* 用哈希的另一半决定横向位置：落在 22% ~ 46% 之间
       * （太靠左 = 玩家刚出发就碰到、还没跑起来；太靠右 = 快到了才拿到、没意义） */
      const frac = hash01(lv.id * 6151 + spawn.x);          // 另一组种子
      const ratio = 0.22 + frac * 0.24;                     // 0.22 ~ 0.46
      const targetCol = Math.max(6, Math.floor(lv.cols * ratio));
      const ground = findGround(lv, targetCol, T);
      if (ground) {
        data.bikes.push({
          x: (targetCol + 0.5) * T - CFG.W / 2,
          y: ground - CFG.H,                  // 站在地面上
          w: CFG.W, h: CFG.H,
          /* ★ 剩余次数：满电 1.0，借一次扣 1/BOOSTS_PER_BIKE，0 = 没电。
           *   用 0~1 的浮点而不是整数次数 —— 渲染层的"电量条"可以直接画，
           *   表现层不用再做一次换算。 */
          charge: 1,
          /* 稳定 id（渲染时用来算轻微浮动动画的相位，避免所有车同步抖） */
          seed: seedBike,
        });
      }
    }
    /* ⚠️ 2026-10-07：**充电桩已按十一要求整体删除**。
     *    这里不再生成 charger；data.chargers 恒为空数组，
     *    渲染层 / 老代码遍历它等于"什么都不做"，向后兼容。 */
    return data;
  }

  /* 在第 col 列往下找"第一个可站的实心面上方"
   * ------------------------------------------------------------
   * ⚠️ 为什么从**上往下**扫：第一个碰到的实心块就是"地面/平台顶"，
   *    它的上方才是能站人的空位。
   * ⚠️ 只认 solids（含 '#'）和 platforms（单向平台）——
   *    不认陷阱/金币，那些不是"能站的东西"。 */
  function findGround(lv, col, T) {
    if (!lv) return null;
    const x = (col + 0.5) * T;
    const cands = [];
    (lv.solids || []).forEach(function (s) {
      if (s.x <= x && s.x + s.w >= x) cands.push(s.y);
    });
    (lv.platforms || []).forEach(function (s) {
      if (s.x <= x && s.x + s.w >= x) cands.push(s.y);
    });
    if (!cands.length) return null;
    cands.sort(function (a, b) { return a - b; });
    /* 取第一个（最高的）—— 车应该刷在"上面那层平台"而不是掉到坑底。
     * ⚠️ 但如果第一个面太高（贴着世界顶部），说明那一列是墙，跳过。 */
    const y = cands[0];
    if (y < T * 3) return null;                    // 太靠上 = 其实是墙
    return y;
  }

  /* ============================================================
   * 每帧更新（在物理之后调用）
   * ============================================================
   * 做两件事：
   *   ① 玩家碰到"还有电"的车 → 借到一次限时加速
   *   ② 加速倒计时递减；归零 → 结束（并记一次提示）
   * ============================================================ */
  function update(p, lv, dt) {
    if (!data || !p) return;

    /* ---------- ① 借车判定 ---------- */
    /* ⚠️ 已经在加速中 / 刚结束还在冷却 → 不再触发。
     *    否则玩家站在车上会"每次都给满 4 秒"，变成无限加速。 */
    if (!(p.boostTimer > 0) && !(p.boostLock > 0)) {
      for (let i = 0; i < data.bikes.length; i++) {
        const b = data.bikes[i];
        if (b.charge <= 0) continue;          // 没电的车借不了
        if (!overlap(p, b)) continue;
        /* ★ 借车：扣掉这台车一次续航，给玩家一段限时加速 ★ */
        b.charge = Math.max(0, b.charge - 1 / CFG.BOOSTS_PER_BIKE);
        p.boostTimer = CFG.BOOST_SECONDS * 60;      // 换算成帧（本项目锁 60fps）
        /* 记一下是哪台车给的 —— 用来画"车身上的能量正在被抽走" */
        p.boostFrom = b;
        if (typeof Sound !== 'undefined' && Sound.scooterOn) Sound.scooterOn();
        break;
      }
    }

    /* ---------- ② 倒计时 ---------- */
    if (p.boostTimer > 0) {
      p.boostTimer--;
      if (p.boostTimer <= 0) {
        /* ★ 加速结束 ★
         * 十一要的反馈：不能"悄悄就没了"。
         * ⇒ 记一个一次性标记，ui 层取走显示一句提示
         *   （见 takeExpired；ui 不取也不影响玩法）。 */
        p.boostTimer = 0;
        p.boostFrom = null;
        p.boostLock = CFG.RELEND_COOL;              // 冷却，防止立刻重新借
        expiredFlag = true;
        if (typeof Sound !== 'undefined' && Sound.scooterOff) Sound.scooterOff();
      }
    }

    /* 冷却递减 */
    if (p.boostLock > 0) p.boostLock--;
  }

  /* 矩形重叠 */
  function overlap(a, b) {
    return a.x < b.x + b.w && a.x + a.w > b.x &&
           a.y < b.y + b.h && a.y + a.h > b.y;
  }

  /* ============================================================
   * 对外的速度倍率（game.js 在算速度时乘上它）
   * ------------------------------------------------------------
   * ⚠️ 这是本模块**唯一**影响物理的地方，而且只是"乘一个系数"。
   *    它**不改任何 CONFIG 数值**、不改跳跃、不改角色属性。
   *
   * ★ 和有电/没电的关系
   *   加速是**限时**的（boostTimer > 0 才有），所以"车没电就加速不了"
   *   是通过"没电的车借不到 ⇒ boostTimer 不会被点亮"来体现的，
   *   这里不需要再判电量。
   * ============================================================ */
  function speedMulFor(p) {
    if (!p || !(p.boostTimer > 0)) return 1;
    /* 最后 1 秒做"车没劲了"的缓出：倍率从 SPEED_MUL 平滑落回 1，
     * 避免速度"啪"地掉回原速（那样像被绊了一跤）。 */
    const tail = 60;                                  // 1 秒
    const t = Math.max(0, Math.min(1, p.boostTimer / tail));
    const ease = 0.35 + 0.65 * t;                     // 最低保留 35% 的加成
    return 1 + (CFG.SPEED_MUL - 1) * ease;
  }

  /* 加速剩余比例 0~1（渲染层画能量条用；没在加速返回 0） */
  function boostRatio(p) {
    if (!p || !(p.boostTimer > 0)) return 0;
    return Math.max(0, Math.min(1, p.boostTimer / (CFG.BOOST_SECONDS * 60)));
  }

  /* 加速剩余秒数（显示给玩家，向上取整 —— "还剩 2 秒"比"1.3 秒"好读） */
  function boostSecondsLeft(p) {
    if (!p || !(p.boostTimer > 0)) return 0;
    return Math.ceil(p.boostTimer / 60);
  }

  /* 取走"加速结束"提示（一次性）。
   * ⚠️ 为什么用"取走"而不是"轮询 + 自己清"：
   *    提示是**瞬态**的，谁先读到谁显示，读完就没了 ——
   *    这样多个调用点也不会重复弹两次。 */
  function takeExpired() {
    if (!expiredFlag) return false;
    expiredFlag = false;
    return true;
  }

  /* 取当前关卡的运行时数据（渲染用） */
  function current() { return data; }

  /* 重置（重新进关时清空，避免上一关的车残留） */
  function reset() { data = null; expiredFlag = false; }

  return {
    CFG: CFG,
    buildForLevel: buildForLevel,
    update: update,
    speedMulFor: speedMulFor,
    boostRatio: boostRatio,
    boostSecondsLeft: boostSecondsLeft,
    takeExpired: takeExpired,
    current: current,
    reset: reset,
    /* 暴露哈希给测试用（验证"按关卡固定"） */
    _hash: hash01,
  };
})();

/* ============================================================
 * 给玩家挂上外卖车相关字段（在 makePlayer 里调用）
 * ------------------------------------------------------------
 * ⚠️ 单独一个初始化函数，而不是散在 makePlayer 里写 ——
 *    这样"删掉本文件就能退回原版"更容易做到
 *    （makePlayer 里只留一行 `typeof initRideState === 'function' && initRideState(p)`）。
 *
 * ⚠️ 字段名从 riding/rideLock 改成 boostTimer/boostLock：
 *    含义务变了（"骑着"→"借到几秒加速"），**名字必须跟着变** ——
 *    留着旧名字会让后来的人以为是同一套逻辑。
 * ============================================================ */
function initRideState(p) {
  if (!p) return;
  p.boostTimer = 0;        // 剩余加速帧数（>0 = 正在加速）
  p.boostLock = 0;         // 加速结束后的"不能再借"冷却帧
  p.boostFrom = null;      // 这次加速是哪台车给的（渲染用）
}
