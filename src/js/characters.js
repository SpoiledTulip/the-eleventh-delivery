/** 合法的 role 白名单（单一真相源，别在别处再写一遍字面量）
 *
 * ★★ 2026-10-06 改成**从 CHARACTERS 自动派生** ★★
 * ------------------------------------------------------------
 * 【踩过的坑】加"美团猴子"时，我把角色配好了、贴图注册了、
 *   墙跳也调通了 —— 但**忘了往这个白名单里加 'monkey'**。
 *   于是 `roleOfSelection()` 把 monkey 判成非法 → **兜底退回袋鼠**。
 *
 *   表现：存档里明明选着猴子，进游戏却是**袋鼠**。
 *   （而且它不报错、不 WARN，静默换人 —— 最难查的那种。）
 *
 * 【为什么改成派生】
 *   手写白名单 = **另一个真相源**。只要项目里存在两个真相源，
 *   加角色时就一定会漏一个 —— 这不是"下次记得"，是设计问题。
 *   ⇒ 现在从 `CHARACTERS` 直接算出来，**再也不可能漏**。
 *
 * ⚠️ `CHARACTERS` 定义在本文件靠上位置，所以这里能直接读它
 *    （顺序：CHARACTERS → VALID_ROLES → roleOfSelection）。
 * ------------------------------------------------------------ */
const VALID_ROLES = CHARACTERS.map(function (c) { return c.role; });

/* ============================================================
 * 查询接口
 * ============================================================ */

/** 按 id 取角色配置。找不到返回 null（调用方要处理）。 */
function charById(id) {
  for (let i = 0; i < CHARACTERS.length; i++) {
    if (CHARACTERS[i].id === id) return CHARACTERS[i];
  }
  return null;
}

/** 按游戏内 role 取角色配置（'kangaroo' / 'dragon'）。
 *
 * ⚠️ role 可能重复（比如未制作的第三角色暂借了 'kangaroo'），
 *    所以**优先返回 ready 的那个** —— 避免拿到空壳配置。 */
function charByRole(role) {
  let fallback = null;
  for (let i = 0; i < CHARACTERS.length; i++) {
    const c = CHARACTERS[i];
    if (c.role !== role) continue;
    if (c.ready) return c;
    if (!fallback) fallback = c;
  }
  return fallback;
}

/** 角色有没有"制作完成"（决定它能不能出现在正式角色库里） */
function charIsReady(id) {
  const c = (typeof id === 'string') ? charById(id) : id;
  return !!(c && c.ready && c.name && c.sprite);
}

/* ============================================================
 * ★ 统一的 role 取值（2026-10-06 新增，接第三个角色时加的）★
 * ============================================================
 * 【为什么需要它】
 *   原来游戏内的 role 分发是**二元的**，到处写着：
 *       Game.pickRole === 'dragon' ? 'dragon' : 'kangaroo'
 *   这种"猜三元"在只有两个角色时能用，但加第三个角色（卡皮巴拉）就废了 ——
 *   选卡皮巴拉会被这个三元强制判成袋鼠，变成"选了卡皮巴拉却玩到袋鼠"（欺骗玩家）。
 *
 * ⇒ 现在统一改成"**从选中的角色配置里取值**"：
 *     查角色表 → 拿它的 role → 拿不到就退回 kangaroo。
 *
 * 【红线（改这个函数时必须守住）】
 *   · 返回值只能是 'kangaroo' / 'dragon' / 'capybara' 三者之一
 *   · **绝不返回 undefined / null / 空字符串** —— 任何异常路径都要兜底到 'kangaroo'
 *   · 不许为了某个角色"能跑"而在这里加特例分支
 *
 * @param selId 角色 id（不传就用存档里当前选中的那个）
 * @return {string} 合法的 role 字符串，一定有值
 * ============================================================ */
function roleOfSelection(selId) {
  let id = selId;

  /* 没传 id → 从存档读"当前选中的角色" */
  if (!id) {
    try {
      if (typeof SAVE === 'function') {
        const s = SAVE();
        if (s && typeof s.selectedChar === 'function') id = s.selectedChar();
      }
    } catch (e) {
      /* 存档读不出来就走下面的兜底 —— 不抛异常 */
    }
  }

  const c = charById(id);
  /* ⚠️ 三重兜底：charById 可能返回 null / role 可能缺失 → 一律退回袋鼠 */
  const role = (c && typeof c.role === 'string' && c.role) ? c.role : '';

  return VALID_ROLES.indexOf(role) >= 0 ? role : 'kangaroo';
}


/** 按 role 取"显示用的名字"（HUD/结算/死亡文案共用）。
 *  ⚠️ 以前这些地方写的是 `role === 'kangaroo' ? '美团袋鼠' : '飞龙宝宝'`，
 *     加了第三个角色后卡皮巴拉会被叫成"飞龙宝宝" —— 所以统一走这里。 */
function displayNameOfRole(role) {
  const c = charByRole(role);
  return (c && c.name) ? c.name : '骑手';
}

/** 按 role 取"主题色"（HUD 卡片、标签用）。
 *  ⚠️ 同理，以前是 `kangaroo ? 黄 : 橙`，卡皮巴拉会用飞龙的橙色。
 *     颜色定义在角色配置里（accentColor），缺省给个中性色。 */
function accentOfRole(role) {
  const c = charByRole(role);
  return (c && c.accentColor) ? c.accentColor : '#9ad0ff';
}

/** 把 `#RRGGBB` 转成 `rgba(r,g,b,alpha)`。
 *  用途：选骑手页的"选中背景"要一层半透明的主色
 *        （直接用 hex 会盖满、看不到角色）。
 *  ⚠️ 传进来的不是合法 hex 时**原样返回**（宁可不变色，也别画成透明/黑块）。 */
function hexToRgba(hex, alpha) {
  if (typeof hex !== 'string') return hex;
  const m = /^#?([0-9a-fA-F]{6})$/.exec(hex.trim());
  if (!m) return hex;
  const n = parseInt(m[1], 16);
  const r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
  const a = (typeof alpha === 'number' && isFinite(alpha)) ? alpha : 1;
  return 'rgba(' + r + ',' + g + ',' + b + ',' + a + ')';
}

/** 按角色播"起跳 / 落地"音效（2026-10-06 新增）。
 * ============================================================
 * 【为什么要做成函数，而不是在 game.js 里写 if】
 *   game.js 里跳跃/落地音效有 4 处调用点（单人 2 处 + 联机 2 处）。
 *   如果每个地方都写 `role === 'capybara' ? Sound.capyJump() : Sound.jump()`，
 *   加第四个角色时必然漏掉一两处 —— 就变成"有的地方有声、有的地方没声"。
 *
 *   ⇒ 统一走这里：调用方只管喊 `playJumpSound(role, 'jump')`，
 *     角色差异集中在这一个函数里，**加角色只改这里一处**。
 *
 * ⚠️ 音效函数可能不存在（audio.js 没加载 / 静音）→ 静默跳过，绝不抛异常。
 * ⚠️ kind: 'jump' | 'land'。二连跳统一用通用音（那是动作反馈，
 *    不属于"角色个性"的一部分）。
 * ============================================================ */
function playJumpSound(role, kind) {
  try {
    if (typeof Sound === 'undefined' || !Sound) return;
    const isCapy = (role === 'capybara');
    const isStitch = (role === 'stitch');
    if (kind === 'land') {
      /* 卡皮巴拉落地更沉（惯性大）；史迪奇落地更轻快（小个子） */
      if (isCapy && typeof Sound.capyLand === 'function') Sound.capyLand();
      else if (isStitch && typeof Sound.stitchLand === 'function') Sound.stitchLand();
      else if (typeof Sound.land === 'function') Sound.land();
      return;
    }
    /* kind === 'jump' */
    if (isCapy && typeof Sound.capyJump === 'function') Sound.capyJump();
    else if (isStitch && typeof Sound.stitchJump === 'function') Sound.stitchJump();
    else if (typeof Sound.jump === 'function') Sound.jump();
  } catch (e) { /* 音效永远不该影响游戏逻辑 */ }
}

/** 给一个"角色卡"元素套上选中态的专属颜色（行内 style）。
 * ============================================================
 * ⚠️⚠️ 为什么要做成函数而不是写 CSS：
 *   选骑手页原来在 CSS 里写死了两段：
 *     .char[data-role="kangaroo"].selected { 黄 }
 *     .char[data-role="dragon"].selected   { 橙 }
 *   **加了卡皮巴拉之后没人补第三段** ——
 *   于是"卡皮巴拉能被选中，但没有高亮框"（十一报的那个 bug）。
 *
 *   ⇒ 改成从角色配置的 accentColor 动态注入，
 *     **以后再加角色不用碰 CSS**（这类"忘了补一段"的错误就不会再犯）。
 * ⚠️ 用行内 style 而不是加 class：行内优先级更高，
 *    能盖掉 `.char.selected` 里的兜底色，不用再写 `!important`。
 * ============================================================ */
function applyCharSelectedStyle(box, role) {
  if (!box || !box.style) return;
  const accent = accentOfRole(role);
  box.style.borderColor = accent;
  box.style.background = hexToRgba(accent, 0.16);
  /* 轻微发光，让"选中"更明显（不依赖颜色也能看出来） */
  box.style.boxShadow = '0 0 0 2px ' + hexToRgba(accent, 0.35);
}

/** 清掉 applyCharSelectedStyle 加的行内样式（切到别的角色时用）。 */
function clearCharSelectedStyle(box) {
  if (!box || !box.style) return;
  box.style.borderColor = '';
  box.style.background = '';
  box.style.boxShadow = '';
}

/**
 * 正式角色库列表 —— **只包含已制作完成的角色**。
 *
 * 这是唯一应该被 UI 用来渲染角色库的入口。
 * 未完成的角色天然被过滤掉，不需要 UI 自己判断。
 */
function listForLibrary() {
  return CHARACTERS.filter(function (c) { return charIsReady(c); });
}

/* ============================================================
 * ★ 玩家「看得见」的角色（2026-10-06 新增）★
 * ============================================================
 * 十一的要求：新角色在解锁之前**一点线索都不给** ——
 * 不要提前显示卡片、不要显示剪影、不要显示"还有 N 名骑手没解锁"，
 * 而是让它在解锁那一刻作为**惊喜**登场。
 *
 * ⇒ 所以 UI 展示角色时有两个不同的口径，别用混：
 *
 *     listForLibrary()    =「已制作完成」（制作视角，给测试/内部用）
 *     listVisibleChars()  =「已制作 + 已解锁」（玩家视角）
 *                           ↑ UI 渲染一律用这个
 *
 * ⚠️ 为什么不在 listForLibrary 里直接过滤已解锁：
 *    它现在的语义是"这个角色做完没有"，测试也在依赖这个语义
 *    （比如 node 层测试没有存档上下文）。
 *    在这里掺进"存档状态"会让测试跑不起来。所以另外开一个函数。
 *
 * ⚠️ 存档读不出来时的兜底原则：**宁可少显示，也不能把没解锁的漏出去** ——
 *    如果拿不到解锁列表，就退回"初始就有的那几个"，
 *    绝不能 fallback 到 listForLibrary()（那会把卡皮巴拉提前卖出去）。
 * ============================================================ */
function listVisibleChars() {
  let unlocked = null;
  try {
    if (typeof SAVE === 'function') {
      const s = SAVE();
      if (s && typeof s.unlockedChars === 'function') unlocked = s.unlockedChars();
    }
  } catch (e) { /* 存档挂了就走兜底 */ }

  /* 拿不到解锁列表 → 只显示初始角色（保守，不剧透） */
  const fallback = defaultUnlockedChars();
  const have = (Array.isArray(unlocked) && unlocked.length) ? unlocked : fallback;

  return listForLibrary().filter(function (c) {
    return have.indexOf(c.id) >= 0;
  });
}

/* ============================================================
 * ★ 常用的前 N 个角色（2026-10-06 十一要求）★
 * ============================================================
 * 十一的原话：
 *   "优化「点击开始跑单」后进入的页面：在该页面顶部**默认只展示四个
 *    角色皮肤**（即玩家最常用的四个皮肤），以直观的方式呈现给玩家。
 *    其余角色不直接显示，玩家可通过打开「角色库」进行浏览与选择。"
 *
 * ------------------------------------------------------------
 * 【排序规则：最近用过 > 用得多 > 解锁顺序】
 * ------------------------------------------------------------
 *   ① **最近用过的排最前**（`Save.data.recentChars`）
 *      —— 玩家这周改玩猴子了，猴子就该冒到前面。
 *        光看累计次数做不到这一点（袋鼠是老玩家最常玩的，
 *        但它可能只是想凑个"全角色通关"）。
 *   ② 没进过 recentChars 的，按 `characterRecords[].uses` 降序
 *      —— 老档刚升级上来时 recentChars 是空的，
 *        用 uses 兜底至少顺序不突兀。
 *   ③ 还平手就按"角色表里的顺序"（= 解锁顺序）
 *      —— 保证结果**稳定**（不会每次刷新都换一个顺序）。
 *
 * ⚠️ 只从"看得见的角色"里挑 —— 绝不能把没解锁的算进来（零剧透红线）。
 * ⚠️ 数量不足 N 时**有几个给几个**（新档只有袋鼠一个，不能凭空补）。
 *
 * @param n 要几个（默认 4）
 * @returns 角色配置数组（最多 n 个）
 * ------------------------------------------------------------ */
function listTopChars(n) {
  const want = (typeof n === 'number' && n > 0) ? n : 4;
  const visible = listVisibleChars();
  if (visible.length <= want) return visible;      // 不足 N 个，全给

  /* 拿"最近用过"的顺序（拿不到就空数组，不影响） */
  let recent = [];
  try {
    if (typeof SAVE === 'function') {
      const s = SAVE();
      if (s && typeof s.recentChars === 'function') recent = s.recentChars();
    }
  } catch (e) { /* 存档读不出来就退化成"按次数排" */ }

  /* 取每个角色的 uses（用于第二排序键） */
  let records = {};
  try {
    if (typeof SAVE === 'function') {
      const s = SAVE();
      if (s && s.data && s.data.characterRecords) records = s.data.characterRecords;
    }
  } catch (e) { records = {}; }

  /* 角色在"角色表"里的原始下标 —— 最终的稳定排序键 */
  const orderOf = {};
  CHARACTERS.forEach(function (c, i) { orderOf[c.id] = i; });

  const ranked = visible.slice().sort(function (a, b) {
    /* ① 最近用过的优先（下标越小越靠前） */
    const ra = recent.indexOf(a.id), rb = recent.indexOf(b.id);
    const aHas = ra >= 0, bHas = rb >= 0;
    if (aHas !== bHas) return aHas ? -1 : 1;       // 用过的排前面
    if (aHas && bHas && ra !== rb) return ra - rb; // 都用过 → 比谁更近

    /* ② 比累计次数 */
    const ua = (records[a.id] && records[a.id].uses) || 0;
    const ub = (records[b.id] && records[b.id].uses) || 0;
    if (ua !== ub) return ub - ua;

    /* ③ 还平手 → 按角色表顺序（保证稳定，不会每次刷新都变） */
    return (orderOf[a.id] || 0) - (orderOf[b.id] || 0);
  });

  return ranked.slice(0, want);
}

/** 初始就拥有的角色（新档默认解锁） */
function defaultUnlockedChars() {
  return CHARACTERS
    .filter(function (c) { return c.unlockedByDefault && charIsReady(c); })
    .map(function (c) { return c.id; });
}

/* ============================================================
 * 角色解锁（★ 每 5 关一个新角色 ★）
 * ============================================================
 * 章节划分：
 *   第 1～5 关   → 第一章
 *   第 6～10 关  → 第二章
 *   第 11～15 关 → 第三章
 *   …每 5 关一章
 *
 * 解锁节点 = 章节最后一关通关时。
 * 配置表里的 unlockLevel 直接写死（5 / 10 / 15），
 * 而不是用公式算 —— 这样以后想把某个角色挪到第 7 关，改一个数字就行。
 * ============================================================ */

/**
 * 通关第 levelIndex 关（0 起算）后，应该解锁哪些角色。
 *
 * @param levelIndex  关卡下标（0 起算）
 * @param alreadyUnlocked  已解锁的 id 数组（避免重复解锁）
 * @return 新解锁的角色配置数组
 *
 * ⚠️ 只返回 **ready === true** 的角色。
 *    未制作的角色解锁了也没意义（进不了角色库、没有形象），
 *    弹一句"新骑手加入"然后点进去是空的，是欺骗玩家。
 *    所以它们会被静默跳过 —— 等做好后改成 ready:true 就自动开始生效。
 */
function charsUnlockedBy(levelIndex, alreadyUnlocked) {
  const done = (levelIndex + 1);       // 1 起算的通关关号
  const have = alreadyUnlocked || [];
  return CHARACTERS.filter(function (c) {
    return c.unlockLevel > 0 &&         // 0 = 初始角色，不需要解锁
           c.unlockLevel === done &&
           c.ready &&                    // ★ 未制作的跳过
           have.indexOf(c.id) < 0;
  });
}

/** 这个角色该在第几关解锁（给"未解锁"提示文案用） */
function charUnlockLevel(id) {
  const c = charById(id);
  return c ? c.unlockLevel : 0;
}

/* ============================================================
 * 角色属性 → 实际游戏数值
 * ============================================================ */

/**
 * 取角色在某一项上的倍率。找不到角色时返回 1（不改变任何东西）。
 * @param id   角色 id 或配置对象
 * @param key  'speedMultiplier' 等
 */
function charMul(id, key) {
  const c = (typeof id === 'string') ? charById(id) : id;
  if (!c) return 1;
  const v = c[key];
  return (typeof v === 'number' && isFinite(v) && v > 0) ? v : 1;
}

/* 兜底访问器 —— 和 SAVE() / DEVICE_STATE() 一个套路。
 * characters.js 没加载成功时，退回"没有倍率加成"的默认值，
 * 游戏照常能玩，只是角色之间没有差异。 */
function CHARS() {
  try {
    if (typeof CHARACTERS !== 'undefined' && Array.isArray(CHARACTERS)) {
      return CHARACTERS;
    }
  } catch (e) { /* 取不到就兜底 */ }
  return [];
}
