const LEVEL_TILE = 32;
const MAP_W = 88;
const MAP_H = 26;

/* 校验并补齐：短了补点，长了截断。
 * 注意：这是兜底，真正应该写对。playtest 会用原始长度报警。 */
function padRow(s) {
  if (s.length >= MAP_W) return s.slice(0, MAP_W);
  var out = s;
  while (out.length < MAP_W) out += '.';
  return out;
}

/* ------------------------------------------------------------
 * 地图构建辅助（供 buildLevel2 这类"生成式关卡"使用）
 * 好处：几何关系由代码保证，不会出现手写点阵的错位问题。
 *
 * ★★ 2026-10-06 扩展：支持**自定义尺寸**（第 13~20 关重构用）★★
 * ------------------------------------------------------------
 * 【为什么需要】原来这几个函数写死用全局 MAP_W/MAP_H（88×26）。
 *   但后期关卡要做得"更长" —— 而 88 列塞不下多区域 + 分支 + 折返，
 *   硬塞就会变成"一条很挤的直线"（十一明确不要这种）。
 *
 *   查证过：**引擎层其实早就不依赖 88 了** ——
 *     · parseLevel() 用的是 `raw.map[0].length` / `raw.map.length`
 *     · 相机边界用 `lv.width` / `lv.height`（render.js）
 *     · 小地图也用 `Game.level.width`（带 88×32 兜底）
 *   ⇒ 只要让**关卡构建**能产出别的尺寸，就能做宽关卡，
 *     完全不用碰 physics.js / render.js / 相机。
 *
 * 【兼容性】这些函数的宽高参数是**可选**的：
 *   · `blankMap()`            → 88×26（和以前完全一样）
 *   · `blankMap(130, 30)`     → 130×30（新用法）
 *   · `put(g,r,c,ch)` 会自动读 `g` 的实际尺寸，
 *     所以**已有的 20 关一行都不用改**。
 * ------------------------------------------------------------ */

/** 一张全空的字符矩阵。传 cols/rows 可以做非 88×26 的地图。 */
function blankMap(cols, rows) {
  const w = (typeof cols === 'number' && cols > 0) ? cols : MAP_W;
  const h = (typeof rows === 'number' && rows > 0) ? rows : MAP_H;
  const g = [];
  for (let r = 0; r < h; r++) g.push(new Array(w).fill('.'));
  /* ★ 把尺寸记在数组上（不占字符位）——
   *   这样 put/hline/rect 不用被逐层传参就能知道边界，
   *   现有调用点（`put(g,...)`）可以完全不改。 */
  g.cols = w;
  g.rows = h;
  return g;
}

/** 读一个地图矩阵的实际尺寸（兼容没打过标记的旧数组） */
function mapSize(g) {
  const rows = g.length;
  const cols = (typeof g.cols === 'number') ? g.cols
    : (rows > 0 ? g[0].length : 0);
  return { cols: cols, rows: rows };
}

/** 在 (r,c) 放一个字符（越界自动忽略） */
function put(g, r, c, ch) {
  const s = mapSize(g);
  if (r >= 0 && r < s.rows && c >= 0 && c < s.cols) g[r][c] = ch;
}

/** 水平铺一条：行 r，列 c1..c2（含） */
function hline(g, r, c1, c2, ch) {
  for (let c = Math.min(c1, c2); c <= Math.max(c1, c2); c++) put(g, r, c, ch);
}

/** 垂直铺一条：列 c，行 r1..r2（含） */
function vline(g, c, r1, r2, ch) {
  for (let r = Math.min(r1, r2); r <= Math.max(r1, r2); r++) put(g, r, c, ch);
}

/** 矩形填充 */
function rect(g, r1, c1, r2, c2, ch) {
  for (let r = Math.min(r1, r2); r <= Math.max(r1, r2); r++) hline(g, r, c1, c2, ch);
}

/** 转成字符串数组 */
function toStrings(g) {
  const s = mapSize(g);
  const out = [];
  for (let r = 0; r < s.rows; r++) {
    /* 每行补齐到 cols（防止某行被写短了导致 parseLevel 读到不同宽度） */
    let row = g[r].join('');
    while (row.length < s.cols) row += '.';
    out.push(row.slice(0, s.cols));
  }
  return out;
}

