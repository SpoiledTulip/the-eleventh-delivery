  vline(g, 42, 19, 20, '#');           // 上方封死

  /* ============================================================
   * ⑥ 第二组开关（右下）—— 要"往下、往右"绕
   * ------------------------------------------------------------
   * 【设计意图】第一个开关在**左上**、第二个在**右下** ——
   *   方向相反，玩家要重新判断一次路线（"这次往哪走？"）。
   *
   * ⚠️ "右下"在横版游戏里就是"走地面、在门右边"。
   *    但门在列 42，右边是**门后的区域**（过不去）……
   *    ⇒ 所以改成"**门前的地面右侧**"：门左边有一块下沉区域，
   *      开关放在地面层但更靠右的位置，需要绕过一些障碍。
   *
   *    更清楚的做法：在门**左侧**做一个"下沉地下室"（行 23 挖空、
   *    行 24 保留地板？不行，行 24 是地板）。
   *    ⇒ 改用在**门前右侧的地面**放开关，中间用砖块隔出"要跳过去"的路径。
   * ============================================================ */
  /* 第二道门前的地面障碍（逼玩家跳/绕，而不是直线走） */
  vline(g, 36, 22, 23, '#');           // 一道矮墙（行22~23，1 格宽）
  hline(g, 22, 37, 40, '=');           // 矮墙上方的单向平台（可跳过去）
  put(g, 21, 38, 'o');                 // 离地 64px（安全）
  /* ★ 第二个开关：放在门前右侧地面，要跳过矮墙才能到 */
  put(g, 23, 40, 't');
  put(g, 22, 40, 'o');                 // 引导金币

  /* ============================================================
   * ⑦ 门后 → 终点（列 43~85）
   * ============================================================ */
  /* ★ 门后主路的金币（设计文档要求全关 22 个）——
   * ⚠️ 全部放在**离地面 ≤200px** 的位置，避开"高处金币"判定。
   *    （离地面 >230px 会被 single-player-test 判成"高处"） */
  put(g, 23, 46, 'o');
  put(g, 22, 48, 'o');
  put(g, 23, 50, 'o');
  put(g, 22, 52, 'o');
  put(g, 23, 54, 'o');
  put(g, 22, 56, 'o');
  /* 一小段断桥（第 4/6 关验证过的机制，做节奏变化） */
  hline(g, 23, 58, 64, 'B');
  /* ⚠️ 断桥下要有地板（行 24 是实心）→ 掉下去摔不死，能走回来 */
  /* 抬高段：金币放在**平台上表面那一行**（离地 160px，安全） */
  hline(g, 20, 66, 72, '=');
