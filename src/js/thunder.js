/* ============================================================
 * thunder.js — ⚡ 雷电气象（2026-10-06 十一要求）
 * ============================================================
 * 十一的需求：
 *   "⚡ 雷电 → 定时落雷，需躲避 → 复用'跳跳怪'的定时预警模式"
 *   并且明确选了："雷电完整做（扣血）"
 *
 * ============================================================
 * 【★ 设计原则（必须遵守）★】
 * ============================================================
 *
 * 【1. 预警时间必须够长 —— 这是"公平"的底线】
 *   落雷不是随机劈人，是"**先在地上画圈警告，0.57 秒后才劈**"。
 *   玩家永远有时间躲开。
 *   ⚠️ 如果把预警时间调到 10 帧（0.17 秒）以下，就变成"运气"了 ——
 *      人根本反应不过来。CONFIG 里注释写明了这个下限。
 *
 * 【2. 落雷位置不能"追着玩家劈"】
 *   如果落点总是玩家脚下，那就是"必胜伤害"，躲无可躲。
 *   ⇒ 落点用**独立的伪随机**（和时间/序号绑定），和玩家位置无关。
 *     玩家可以学会"看预警圈 → 挪开"。
 *
 * 【3. 落雷要"看得见"】
 *   预警期：地面画一个醒目的圈（黄→红渐变 + 闪烁）
 *   落雷瞬间：一道竖雷 + 屏幕闪 + 震动
 *   没有视觉提示的伤害 = 玩家觉得"莫名其妙就死了"。
 *
 * ============================================================
 * 【独立性设计（按项目规范）】
 * ============================================================
 * 这个模块**不侵入 game.js 的物理段**，只做三件事：
 *   · update(lv, dt)  —— 推进雷电状态机（由 game.js 调用）
 *   · draw(ctx, t, lv) —— 画预警圈和雷（由 render.js 调用）
 *   · reset()          —— 换关时清状态
 * ⇒ 想删掉雷电，只需在 game.js / render.js 各去掉一处调用，
 *   游戏立刻退回"没有雷电"的版本。
 *
 * ⚠️ 依赖注入：伤害回调从外面传进来（不直接调 damagePlayer），
 *    这样这个文件不依赖 game.js 的内部函数，能单独测。
 * ============================================================ */
const THUNDER = (function () {

  /* ============================================================
   * ★★★ 2026-10-07 大修：修掉 4 个缺陷（十一报"没被雷劈到却扣血"）★★★
   * ============================================================
   * 原版有三个"自己和自己打架"的地方，导致玩家"明明躲开了、
   * 甚至飞到天上，血还是掉了"。逐一说明：
   *
   * ① 伤害判定只比横向（原 `Math.abs(pcx - hitX) < 34`）
   *    ⇒ 不管玩家在纵向的哪儿（高空 / 坑底）都算命中。
   *    实测：落点 176.8 时，玩家在 y=20（地图顶端，离落点 720px）
   *    照样扣血。
   *    **修法：改成真正的矩形相交（横向 + 纵向都判）。**
   *
   * ② 落点"追着玩家劈"（原 `baseX = p0.x + p0.w/2`）
   *    ⇒ 和本文件开头的"原则 2"直接矛盾：落点永远在玩家 ±260px 内，
   *      "跑到别处躲开"根本不成立。
   *    **修法：落点改用"和玩家无关的锚点池"——沿关卡宽度等距布点，
   *      按序号取。玩家位置完全不参与。**
   *
   * ③ 伪随机失效（原 `+ state.strikes.length`）
   *    ⇒ strikes 数组每轮会被删空归零，于是每轮的 step 都相同。
   *      实测跑 3000 帧（13 次落雷），落点永远是同一个值。
   *    **修法：用"只增不减"的计数器 strikeIndex 当序号。**
   *
   * ④ 视觉与判定坐标系不一致（绘制在 render.js，本次一并修）
   *    雷柱画在 `CANVAS_H * 0.72`（固定**屏幕**高度），判定用**世界坐标**。
   *    关卡高 832~1344px 要滚屏 ⇒ 视觉落点和判定位置错位。
   *    **修法：绘制的纵向位置改成由世界坐标换算。**
   *
   * ⚠️ 红线：**没有改 physics.js 里任何雷电数值**
   *    （WEATHER_THUNDER_WARN / INTERVAL / DAMAGE 一个都没动），
   *    只改了判定逻辑和落点生成方式。
   * ⚠️ 新加的 `COL_H` 只放在本文件里当局部常量，不写进 CONFIG
   *    （避免污染物理参数表）。
   * ============================================================ */

  /* 雷柱的"纵向判定高度"（px）——从地面往上这么高的一段都算危险区。
   * ★ 这个值要和 render.js 画的雷柱长度**保持一致**，
   *   否则又会出现"看到的位置 ≠ 判定的位置"（就是缺陷 ④）。
   * 取 320px = 10 格：比玩家跳跃高度（133px）高得多，
   * 意味着"站在地面上躲不掉，必须横向挪开"——这才是雷电的玩法。 */
  const COL_H = 320;

  /* 雷电状态（每关重置）
   *   timer       —— 距离下一次落雷还有多少帧
   *   phase       —— 'idle'（等下次）| 'warn'（预警中）
   *   warnLeft    —— 预警还剩多少帧
   *   strikes     —— 当前存在的落雷标记（画用）
   *   seed        —— 关卡种子（保证同一关的落点序列稳定、可学习）
   *   strikeIndex —— ★ 落雷序号（只增不减，用来生成"每次都不同"的落点）
   *   anchors     —— ★ 落点候选池（和玩家无关，进关时按关卡宽度生成）
   *   groundY     —— ★ 当前关卡"地面顶面"的世界 y（判定危险区的基准） */
  let state = {
    timer: 0,
    phase: 'idle',
    warnLeft: 0,
    strikes: [],
    seed: 1,
    active: false,
    strikeIndex: 0,
    anchors: [],
    groundY: 0,
    lastHitX: null,
  };

  /** 换关 / 进新一单时重置 */
  function reset(lv) {
    state.timer = 60;          // 进关后先给 1 秒缓冲，别一进来就劈
    state.phase = 'idle';
    state.warnLeft = 0;
    state.strikes = [];
    state.active = false;
    state.pending = null;
    state.lastHitX = null;
    /* 用关卡索引做种子：同一关的落点序列一致（玩家能学会规律）。
     * ⚠️ 不用 Math.random 做种子 —— 那样每局都不一样，没法"学会"，
     *    就退化成纯运气了。 */
    state.seed = (lv && typeof lv.index === 'number') ? (lv.index + 1) * 7919 : 7919;

    /* ★ 缺陷 ③ 修复：序号计数器归零 */
    state.strikeIndex = 0;

    /* ★ 缺陷 ② 修复：落点候选池（和玩家无关）
     * ------------------------------------------------------------
     * 原来落点 = 玩家位置 ±260px（追着劈）。
     * 现在改成**和玩家无关**的等距锚点：
     *   沿关卡宽度每 ANCHOR_STEP px 放一个候选点，落雷时按序号取。
     *   ⇒ 玩家站在哪儿都改不了落点 ⇒ "看预警圈 → 挪开"这个玩法成立。 */
    const W = (lv && lv.width) ? lv.width : 3000;
    /* ★★ 2026-10-07：锚点间距 340 → 120 → **68**
     * ------------------------------------------------------------
     * 【为什么必须一缩再缩】
     *   伤害判定区宽 **68px**（±34px）。
     *   · 340px 间距 ⇒ 最大偏差 170px ⇒ 几乎全劈空
     *   · 120px 间距 ⇒ 最大偏差 **60px** ⇒ 仍超出 34px ⇒ 约一半劈空
     *     （实测：玩家 x=413 时最近锚点是 360，偏差 -53 ⇒ 0% 命中）
     *   · 68px 间距 ⇒ 最大偏差 **34px** ⇒ **刚好落在判定区边缘**
     *     ⇒ 站着不动/匀速直行基本必中，**变向/急停仍能躲开**
     *
     * ⚠️ 间距 == 判定宽度，看起来"刚好必中"？**不是**：
     *   落点是在**预警开始那一刻**用"当前速度"预判的；
     *   玩家只要在 0.57 秒内**变速/急停/上高台**，预判就落空。
     *   ⇒ 命中率高，但"会动的玩家"依然躲得掉。
     * ============================================================ */
    const ANCHOR_STEP = 68;
    const anchors = [];
    for (let x = ANCHOR_STEP; x < W - ANCHOR_STEP; x += ANCHOR_STEP) anchors.push(x);
    /* 兜底：关卡太窄时至少给 3 个点 */
    if (anchors.length < 3) {
      anchors.length = 0;
      for (let i = 1; i <= 3; i++) anchors.push(W * i / 4);
    }
    state.anchors = anchors;

    /* ★ 缺陷 ① 修复所需：记下"地面在世界坐标的哪个 y"。
     *   判定危险区 = 从 groundY 往上 COL_H 的一段。 */
    state.groundY = (lv && lv.rows) ? (lv.rows - 2) * 32 : 0;
  }

  /** 稳定伪随机（同一 seed+序号 ⇒ 同一结果，可复现可学习） */
  function rnd(n) {
    const x = Math.sin(state.seed * 12.9898 + n * 78.233) * 43758.5453;
    return x - Math.floor(x);
  }

  /** 角色矩形 */
  function playerBox(p) {
    return { x: p.x, y: p.y, w: p.w || 26, h: p.h || 32 };
  }

  /* ============================================================
   * ★ 取"玩家附近可见窗口内"的锚点（2026-10-07 第三次修正）
   * ============================================================
   * 【为什么需要这个】
   *   上一版从**全关锚点池**里取落点 ⇒ 落点常常在屏幕外
   *   （第 12 关宽 2816px，屏幕只显示 1280px）
   *   ⇒ 玩家看不到预警圈，也就"看不见雷电特效"。
   *
   * 【做法】
   *   ① 以玩家为中心，取左右各 VIS_HALF 的范围（略大于半屏）
   *   ② 把**落在关卡内的锚点**筛出来
   *   ③ 如果这个范围里一个锚点都没有（比如玩家在关卡边缘），
   *      就退化成"用玩家位置对齐到最近的网格点"—— 保证永远有解
   *
   * ⇒ 落点仍在**固定网格**上（不是玩家位置）⇒ 可预判、可躲；
   *   但一定在**画面内** ⇒ 看得见预警圈。
   * ============================================================ */
  const VIS_HALF = 520;      // 玩家左右各 520px（比半屏 640 略窄，留点余量）

  /** ★ 取"玩家附近的锚点"，并按**预判位置**排序（越接近预测点越优先） */
  function nearbyAnchors(aimX) {
    const all = state.anchors;
    if (!all.length) return [0];
    /* 没有玩家（异常情况）→ 退回全池 */
    const p0 = (typeof Game !== 'undefined' && Game.players && Game.players[0]) || null;
    if (!p0) return all;

    const center = p0.x + (p0.w || 26) / 2;
    const near = [];
    for (let i = 0; i < all.length; i++) {
      if (Math.abs(all[i] - center) <= VIS_HALF) near.push(all[i]);
    }
    if (!near.length) {
      /* 兜底：附近没有锚点（玩家在很边上的位置）——
       * 用"离玩家最近的那个锚点"当作唯一候选，
       * 这样至少不会掉进"空池"。 */
      let best = all[0], bestD = Math.abs(all[0] - center);
      for (let i = 1; i < all.length; i++) {
        const d = Math.abs(all[i] - center);
        if (d < bestD) { bestD = d; best = all[i]; }
      }
      return [best];
    }

    /* ★★ 2026-10-07 新增：按"离预测落点的距离"排序 ★★
     * 预判点附近一定有几个锚点，优先在它们里挑 ⇒ 命中率大幅提高。
     * ⚠️ 仍然返回**锚点**（不是预测坐标本身），保住"离散、可预判"的性质。 */
    if (typeof aimX === 'number') {
      near.sort(function (a, b) {
        return Math.abs(a - aimX) - Math.abs(b - aimX);
      });
    }
    return near;
  }

  /** ★ 雷击危险区（世界坐标矩形）：横向以 hitX 为中心宽 68px，纵向从地面往上 COL_H */
  function strikeBox(hitX, groundY) {
    return { x: hitX - 34, y: groundY - COL_H, w: 68, h: COL_H };
  }

  /** AABB 相交（和 ch3-mechanics.js 的 overlap 同口径） */
  function overlap(a, b) {
    return a.x < b.x + b.w && a.x + a.w > b.x && a.y < b.y + b.h && a.y + a.h > b.y;
  }

  /**
   * 推进雷电（每帧调用）
   * @param lv     当前关卡
   * @param damage 伤害回调 (player) => void（由 game.js 注入）
   */
  function update(lv, damage) {
    if (!lv || lv.weather !== 'thunder') {
      state.active = false;
      state.strikes = [];
      return;
    }
    state.active = true;

    /* 落雷标记的存活时间（画用，和伤害判定解耦） */
    for (let i = state.strikes.length - 1; i >= 0; i--) {
      state.strikes[i].life--;
      if (state.strikes[i].life <= 0) state.strikes.splice(i, 1);
    }

    if (state.phase === 'idle') {
      state.timer--;
      if (state.timer <= 0) {
        /* ★★ 进入预警：**在预警开始这一刻**就把落点定死（原则 2）★★
         * ------------------------------------------------------------
         * 【两次修正的来龙去脉（别改回去）】
         *   ① 最初：落点 = 玩家位置 ±260px。
         *      问题：**追着玩家劈**，"跑到别处躲开"不成立（缺陷 ②）。
         *   ② 上一版：落点 = 全关等距锚点池（每 340px 一个）。
         *      问题：**大半落点在屏幕外**！第 12 关宽 2816px，
         *      玩家在 x=47 时落点可能在 x=1700 ⇒ 屏幕上什么都看不到
         *      （十一报"还是看不见雷电特效"）。
         *   ③ 现在（正解）：**在"玩家附近的可见窗口"里取锚点**。
         *      · 锚点仍是固定的 340px 网格（不是玩家位置）⇒ 能预判、能躲
         *      · 但只从"玩家左右各半屏"范围内的锚点里挑
         *        ⇒ **保证落点一定在画面上**，玩家看得见预警圈
         *      · 同时**不排除玩家脚下**（近的锚点也在池里）
         *        ⇒ 保留"必须挪开"的紧张感
         * ------------------------------------------------------------ */
        /* ★★★ 2026-10-07：落点改成"**预判玩家移动**"（十一要求）★★★
         * ------------------------------------------------------------
         * 【为什么改】
         *   之前落点只从锚点池里按序号取，**完全不看玩家在往哪跑**
         *   ⇒ 玩家稍微挪一下就躲开了，雷几乎打不到人（难度太低）。
         *   十一明确要求："雷的降落位置应根据目标的移动方向和速度进行预判，
         *   而不是落在目标的当前位置"。
         *
         * 【怎么预判】
         *   ① 读取玩家**当前水平速度** `p.vx`（px/帧）
         *   ② 预测它在"预警结束那一刻"会在哪：
         *        aimX = 玩家中心 + vx × 预警帧数 × 提前量系数
         *      ⚠️ 提前量系数 < 1 —— 玩家通常会**中途变向/急停**，
         *         满额预判会劈得太靠前、反而打不中。
         *   ③ 把预判点**吸附到最近的锚点**（保留"离散可学习"的优点）
         *   ④ 再在"离预判点最近的 2 个锚点"里随机挑一个
         *      ⇒ 既保证命中率，又不会每次都劈同一个坐标
         *
         * 【为什么还要吸附锚点、而不是直接用 aimX】
         *   直接用连续坐标 = "必中"，玩家会觉得被耍（没有躲的余地）。
         *   吸附到网格后，落点是**可学习、可预判**的，
         *   玩家能通过"变向/急停/上高台"来骗过预判 —— 这才有博弈感。
         * ============================================================ */
        const lead = (typeof Game !== 'undefined' && Game.players && Game.players[0]) || null;
        const pvx = lead ? (lead.vx || 0) : 0;
        const pcent = lead ? (lead.x + (lead.w || 26) / 2) : null;
        /* ============================================================
         * ★★★ 预判参数（2026-10-07 调校，十一要"更难命中/预判移动"）★★★
         * ============================================================
         * LEAD_RATIO：把"预警 0.57 秒内的位移"按这个比例计入预判。
         *   · =1.0 → 满额预判。但玩家常中途急停/变向 ⇒ 会劈空
         *   · 太大 → 玩家一停就劈到身后，反而更难中
         *   · 0.85 实测最平衡：继续跑的被劈中，急停的能躲开
         * ★ 另外加"**慢速贴身**"：玩家速度很小时，落点直接压到他身上，
         *   避免"站着不动也被劈偏 27px"（那会让玩家觉得判定莫名其妙）。
         * ============================================================ */
        const LEAD_RATIO = 0.85;
        let aimX = null;
        if (pcent != null) {
          const lead0 = pvx * CONFIG.WEATHER_THUNDER_WARN * LEAD_RATIO;
          /* 慢速（|vx| < 1.2 px/帧 ≈ 慢走）→ 不预判，直接压身上 */
          aimX = pcent + (Math.abs(pvx) < 1.2 ? 0 : lead0);
        }

        const pool = nearbyAnchors(aimX);
        /* ============================================================
         * ★ 选落点：**优先取离预判点最近的锚点**（命中率优先）
         * ============================================================
         * 【为什么不再"随机挑"】
         *   上一版在"最近 2 个锚点"里轮换 ⇒ 有一半时候取到较远的那个，
         *   落点离玩家 ≥ 60px ⇒ 超出 ±34 判定区 ⇒ **劈空**。
         *   十一要求"更容易击中人"，所以改成**直接取最近的那个**。
         *
         * 【怎么保留"可躲"】
         *   ① 锚点间隔 120px > 判定宽度 68px ⇒ 落点不会精确锁头；
         *   ② **玩家在预警 0.57 秒内急停/变向/上高台，就能躲开**
         *      （预判是按"匀速直行"算的，一变速就错）。
         *   ⇒ 命中率高，但**不是必中** —— 这才是要的博弈感。
         * ============================================================ */
        const idx0 = (typeof aimX === 'number')
          ? 0                                     /* pool 已按"离预判点"排序 ⇒ 第 0 个最近 */
          : Math.floor(rnd(state.strikeIndex * 7 + 3) * pool.length) % pool.length;
        let hitX = pool[idx0];
        /* ============================================================
         * ⚠️ 2026-10-07：**删掉了"回避上一次落点"逻辑**
         * ============================================================
         * 【为什么删】
         *   原来"连续两次落点太近就换到 pool[1]" ⇒ 玩家**站着不动**时
         *   两次预判点必然重合 ⇒ 每次都跳到次近锚点 ⇒ 实测偏差 -113px
         *   ⇒ **站着不动反而 0% 命中**（与"提高命中率"完全相反）。
         *
         * 【为什么不可惜】
         *   玩家不动 → 雷就劈在他所在的那一列，**这本来就是对的**
         *   （而且更符合"站着不动很危险"的压迫感）。
         *   视觉上也不会奇怪：雷是"同一片区域被连续打击"，很自然。
         * ============================================================ */
        state.pending = { x: hitX };
        state.phase = 'warn';
        state.warnLeft = CONFIG.WEATHER_THUNDER_WARN;
      }
      return;
    }

    if (state.phase === 'warn') {
      state.warnLeft--;
      const tg = state.pending;

      if (state.warnLeft <= 0) {
        /* ★ 落雷 ★ */
        const hitX = tg ? tg.x : 0;
        const groundY = lv.rows ? (lv.rows - 2) * 32 : state.groundY;
        state.strikes.push({ x: hitX, groundY: groundY, life: 18, maxLife: 18 });
        state.phase = 'idle';
        state.timer = CONFIG.WEATHER_THUNDER_INTERVAL;
        state.pending = null;
        state.lastHitX = hitX;
        state.strikeIndex++;              /* ★ 序号只增不减（修缺陷 ③） */

        /* 屏幕反馈：闪电该有一下白闪 + 震动 */
        Game.screenFlash = Math.max(Game.screenFlash || 0, 0.55);
        Game.shake = Math.max(Game.shake || 0, 9);

        /* ============================================================
         * ★★★ 伤害判定（2026-10-07 重写）★★★
         * ============================================================
         * 【原来错在哪】只比横向距离 `|pcx - hitX| < 34`，
         *   完全没有纵向判断 ⇒ 玩家飞到地图顶端也会被劈中。
         *
         * 【现在】用**真正的矩形相交**：
         *   危险区 = 以 hitX 为中心、宽 68px、从地面往上 COL_H(320px)
         *   命中条件 = 玩家包围盒和这个矩形相交
         *   ⇒ 横向要够近 **且** 纵向在雷柱高度内，才算被劈中。
         *
         * ⚠️ 为什么纵向不是"从天上一直到地面"：
         *   那样玩家跳到空中反而更危险，不合直觉。
         *   真实的雷是"从云里劈到地面"，危险区就是**近地面那一段**。
         *   这让"站在高台上"变成有效的躲法。
         * ============================================================ */
        if (typeof damage === 'function' && Game.players) {
          const zone = strikeBox(hitX, groundY);
          for (let i = 0; i < Game.players.length; i++) {
            const p = Game.players[i];
            if (!p || p.dead || p.hearts <= 0) continue;
            if (overlap(playerBox(p), zone)) {
              damage(p, CONFIG.WEATHER_THUNDER_DAMAGE, 'thunder');
            }
          }
        }
      }
    }
  }

  /** 当前是否有活跃预警（给 HUD 提示用，可空） */
  function isWarning() {
    return state.active && state.phase === 'warn';
  }

  /** 预警剩余帧数（画用） */
  function warnFramesLeft() {
    return state.phase === 'warn' ? state.warnLeft : 0;
  }

  /** 当前预警目标（画圈用） */
  function pendingTarget() {
    return state.pending || null;
  }

  /** 当前落雷标记（画用） */
  function strikes() {
    return state.strikes;
  }

  /** ★ 落雷危险区的高度（render.js 画雷柱时要和它对齐，修缺陷 ④） */
  function columnHeight() {
    return COL_H;
  }

  return {
    reset: reset,
    update: update,
    isWarning: isWarning,
    warnFramesLeft: warnFramesLeft,
    pendingTarget: pendingTarget,
    strikes: strikes,
    columnHeight: columnHeight,
    /* ★ 关卡全锚点池（测试用：验证"落点永远落在预设锚点上"） */
    anchorList: function () { return state.anchors.slice(); },
  };
})();
