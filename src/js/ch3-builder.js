/** 封口：地图左右两侧的墙（防止玩家跑出地图）—— 项目的既有教训 */
function ch3Seal(g) {
  const s = mapSize(g);
  vline(g, 0, 0, s.rows - 1, '#');
  vline(g, s.cols - 1, 0, s.rows - 1, '#');
  /* ★ 顶部也要封 —— 否则玩家能从最上面跳出地图 */
  hline(g, 0, 0, s.cols - 1, '#');
}

