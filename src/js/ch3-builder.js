function ch3Gap(g, r, c1, c2) {
  hline(g, r, c1, c2, '.');
  hline(g, r + 1, c1, c2, '.');
  sealBottom(g, c1, c2);
}

/**
 * 保住地图底部封底（最后两行铺实）
 * ------------------------------------------------------------------
 * 【为什么要有这个东西】
 *   任何"向下挖"的构件（坑/竖井/大缺口）都有可能挖到地图底部。
 *   一旦把 `ch3Base` 铺的**底线**挖穿，玩家就会掉出世界 ——
 *   而且这类 bug 在地形图上只是少两个 `#`，**极难肉眼发现**。
 *   ⇒ 所有向下挖的函数末尾都调一次它，一劳永逸。
 * ------------------------------------------------ */
function sealBottom(g, c1, c2) {
  const sz = mapSize(g);
  hline(g, sz.rows - 1, c1, c2, '#');
  hline(g, sz.rows - 2, c1, c2, '#');
}

