/* ============================================================
 * ★★★ 高级动作构件（2026-10-07 新增）★★★
 * ============================================================
 * 十一的诉求原文：
 *   "不是角色能力太强，而是 13~20 关仍然按普通平台跳跃的地形标准设计。"
 *   "每关必须至少包含：需要二段跳修正落点的区域 / 需要墙滑或墙跳的区域 /
 *     需要冲刺才能稳定通过的区域 / 至少一个不能靠普通跑跳无脑通过的招牌场景。"
 *
 * ------------------------------------------------------------
 * ★★ 设计这些构件用的"硬数字"（用 tools/_ch3-reach.js 实测得出）
 * ------------------------------------------------------------
 *   （别信几何估算 —— 我第一版估的差了一倍。这些是逐帧积分跑出来的。）
 *
 *   | 动作            | 水平跨越   | 垂直上升  |
 *   |-----------------|-----------|----------|
 *   | 单跳            | 3.38 格   | 2.99 格  |
 *   | + 二段跳        | 5.44 格   | 5.39 格  |
 *   | + 空中冲刺      | 5.22 格   | —        |
 *   | 跳+二段跳+冲刺  | 7.84 格   | 5.99 格  |
 *   | 一次冲刺（平地）| 3.44 格   | —        |
 *   | 跳 + 向上冲刺   | —         | 12.26 格 |
 *   | 单次墙跳净上升  | —         | 4.30 格  |
 *
 *   ⇒ 结论（这几个数字是构件的**默认参数来源**）：
 *     · **> 3.4 格**的缺口 = 单跳过不去
 *     · **> 5.5 格**的缺口 = 连二段跳都过不去 ⇒ **必须冲刺**
 *     · 台阶高 **> 3.0 格** = 单跳上不去 ⇒ 要二段跳/墙跳
 *     · 竖井**宽 3~4 格**、深 ≥ 8 格 = 只能墙跳
 * ============================================================ */

/**
 * ★ 墙跳竖井 —— 两面高墙夹一条窄缝，**只能靠墙跳爬上去**
 * ------------------------------------------------------------------
 * 【为什么需要它】
 *   实测审计发现 13~20 关的**竖井数量 = 0** ——
 *   也就是说"墙滑/墙跳"这两个能力**从来没有被地形强制要求过**。
 *   这是本轮最核心的缺口。这个构件就是补它的。
 *
 * 【构造要点（都有讲究）】
 *   ① 左右墙必须**连续**（中间不能有断口，否则玩家能从断口跳出去）
 *   ② 井底要**实心**（玩家掉进去不会摔出世界）
 *   ③ 井顶必须有**出口**（爬上来后能走出去）
 *   ④ ⚠️ **出口方向要明确** —— 井顶一侧开口，
 *      另一侧用墙挡住，否则玩家爬上来不知道该往哪走
 *   ⑤ ⚠️ **宽度 3~4 格**：太窄（2 格）墙跳没有水平空间；
 *      太宽（>5 格）换边太慢，爬升效率反而下降
 *
 * @param g      地图矩阵
 * @param cL     左墙列
 * @param cR     右墙列（井的内宽 = cR - cL - 1）
 * @param rBottom 井底行（实心地面顶面）
 * @param rTop    井顶行（出口所在行）
 * @param exitSide 'left' | 'right' —— 出口开在井顶的哪一侧
 */
function ch3Shaft(g, cL, cR, rBottom, rTop, exitSide) {
  /* 左墙、右墙（从井顶往上多留 1 格，让玩家爬上来时有落脚） */
  vline(g, cL, rTop, rBottom, '#');
  vline(g, cR, rTop, rBottom, '#');
  /* 井底实心（防止摔出去） */
  hline(g, rBottom, cL, cR, '#');
  hline(g, rBottom + 1, cL, cR, '#');
  /* ★ 同步保住地图封底 */
  sealBottom(g, cL, cR);
  /* 井内清空（防止之前铺的地面留在井里挡住攀爬） */
  for (let r = rTop; r < rBottom; r++) {
    hline(g, r, cL + 1, cR - 1, '.');
  }
  /* 井顶出口平台（两侧都铺，玩家自己选方向） */
  hline(g, rTop - 1, cL - 3, cR + 3, '#');
  /* ★ 出口方向：在"非出口"那一侧多堆一堵墙，逼玩家往指定方向走 */
  if (exitSide === 'right') {
    vline(g, cL - 3, rTop - 5, rTop - 2, '#');
  } else if (exitSide === 'left') {
    vline(g, cR + 3, rTop - 5, rTop - 2, '#');
  }
}

/**
 * ★ 大缺口 —— **单跳/二段跳都过不去，必须空中冲刺**
 * ------------------------------------------------------------------
 * 【默认宽 7 格的理由】
 *   二段跳上限 5.44 格、跳+冲刺 5.22 格、全连招 7.84 格。
 *   7 格刚好落在"二段跳不够、但跳+二段跳+冲刺够"的区间
 *   ⇒ **强制玩家用冲刺**，且留了 0.8 格的容错。
 *
 * ⚠️ **必须给"检查点/回退路径"**：十一要求
 *   "失败后能从附近检查点重来""玩家能看懂自己为什么失败"。
 *   所以缺口两侧要有明显的高度差或颜色提示，别做成"看不到对面"。
 *
 * @param gapTiles 缺口宽度（格）。默认 7 = 必须冲刺
 * @param landCols 缺口中间/对面要不要给落脚点（0 = 不给，必须一口气冲过去）
 */
function ch3Chasm(g, r, c1, gapTiles, landCols) {
  const w = (gapTiles == null) ? 7 : gapTiles;
  /* 把这一行连同下面 2 行都挖空（挖浅了玩家会"贴地划过去"） */
  for (let k = 0; k < 3; k++) {
    hline(g, r + k, c1, c1 + w - 1, '.');
  }
  /* ⚠️⚠️ 挖完之后必须**保住地图底部的封底**，否则玩家掉出世界。
   *   （踩过：挖到倒数第 1~2 行时，`ch3Base` 铺的底线被挖穿，
   *     地形图上能看到 row 28/29 出现 `.` 洞。）
   *   ⇒ 这里无条件把"最后两行"重新铺实。 */
  sealBottom(g, c1, c1 + w - 1);
  /* 可选：缺口中间给一格落脚（做"两段冲刺"的变体） */
  if (landCols && landCols > 0) {
    const mid = c1 + Math.floor(w / 2);
    hline(g, r + 1, mid, mid + landCols - 1, '#');
  }
  return c1 + w;   // 返回对岸起始列，方便连续拼接
}

/**
 * ★ 错层平台链 —— **必须用二段跳修正落点**
 * ------------------------------------------------------------------
 * 【构造逻辑】
 *   一串水平错开、垂直交替的小平台。相邻两个平台：
 *     · 水平差 2~3 格（单跳够得到）
 *     · 垂直差 3~4 格（**单跳 2.99 格上不去 ⇒ 必须二段跳**）
 *     · 而且方向左右交替（逼玩家"跳→修正方向→再跳"）
 *
 * @param n        平台个数
 * @param stepC    水平间隔（格）
 * @param stepR    垂直落差（格，正数 = 往上）
 * @param upFirst  true = 第一个平台更高
 */
function ch3Zigzag(g, r, c1, n, stepC, stepR, upFirst) {
  const sc = (stepC == null) ? 3 : stepC;
  const sr = (stepR == null) ? 3 : stepR;
  let cc = c1, rr = r;
  for (let i = 0; i < n; i++) {
    /* 平台本身 3 格宽 —— 太窄了玩家落点容错不够会烦躁 */
    hline(g, rr, cc, cc + 2, '#');
    /* 方向交替：偶数往右、奇数往左（形成"之"字） */
    const dir = (i % 2 === 0) ? 1 : -1;
    cc += dir * sc;
    const up = (upFirst ? (i % 2 === 0) : (i % 2 === 1));
    rr += up ? -sr : sr;
  }
}

/**
 * ★ 墙滑窄缝 —— 一条**又深又窄**的垂直缝，玩家只能贴着墙滑下去
 * ------------------------------------------------------------------
 * 【为什么不用普通坑】普通坑玩家会直接自由落体。
 *   这条缝的两壁是实心墙，玩家落进去时**必然贴墙**
 *   ⇒ 触发滑墙（wallSlideSpeed = 1.33 px/帧，比自由落体慢得多），
 *   玩家能从缝底安全到达，同时**学会"贴墙能减速"**。
 *
 * @param cL,cR  缝的左右壁列（缝宽 = cR - cL - 1）
 * @param rTop   缝口行
 * @param rBottom 缝底行（缝底要实心，别让玩家摔出世界）
 */
function ch3WallGap(g, cL, cR, rTop, rBottom) {
  vline(g, cL, rTop, rBottom, '#');
  vline(g, cR, rTop, rBottom, '#');
  for (let r = rTop; r < rBottom; r++) {
    hline(g, r, cL + 1, cR - 1, '.');
  }
  /* 缝底：实心，且**往一侧开口**（滑到底必须能走出去） */
  hline(g, rBottom, cL, cR, '#');
  hline(g, rBottom + 1, cL, cR, '#');
  sealBottom(g, cL, cR);
}

/**
 * ★ 斜向路线 —— 从墙面冲刺到（移动）平台
 * ------------------------------------------------------------------
 * 【十一的点名要求】
 *   "需要从墙面冲刺到移动平台的斜向路线"（长文二·第五点）
 *
 * 做法：在墙上放一段可站的小平台（起跳点），
 *   斜上方 4~5 格处放目标平台（**单跳够不到，必须斜向冲刺**）。
 *   因为单跳 3.38 格、二段跳 5.44 格，取 斜向 5 格 + 上 4 格
 *   ⇒ 二段跳的"水平够但垂直不够"，斜冲（水平 7.12 + 上 7.10）刚好过。
 *
 * @param wallC   墙面所在列
 * @param wallR   墙面上的立足行
 * @param dir     +1 = 目标在墙的右侧，-1 = 左侧
 */
function ch3Diagonal(g, wallC, wallR, dir) {
  const d = (dir == null) ? 1 : dir;
  /* 墙上的起跳小台（2 格） */
  hline(g, wallR, wallC + (d > 0 ? 1 : -2), wallC + (d > 0 ? 2 : -1), '#');
  /* 目标平台：斜上 4 行、水平 5 格 —— 单跳/二段跳都差一点，必须斜冲 */
  const tr = wallR - 4;
  const tc = wallC + d * 6;
  hline(g, tr, Math.min(tc, tc + 2 * d), Math.max(tc, tc + 2 * d), '#');
  return { r: tr, c: tc };
}

/**
 * ★ 连续动作链标记 —— 一串"必须按顺序做"的落脚点
 * ------------------------------------------------------------------
 * 【十一的要求】
 *   "至少一个必须正确选择动作顺序的连续动作段。动作顺序不能全部互相替代。"
 *   例：先墙滑降速 → 再墙跳获高度 → 再二段跳修正 → 最后冲刺落移动平台。
 *
 * 做法：按给定的 (行, 列) 序列铺小平台，**相邻两个都超出单跳能力**
 *   （要么水平 > 3.4 格、要么垂直 > 3.0 格），
 *   而且每个平台**只有 2 格宽**（落点要精确）。
 *
 * @param pts 数组：[{r, c, w}] w 默认 2
 */
function ch3Chain(g, pts) {
  pts.forEach(function (p) {
    const w = p.w || 2;
    hline(g, p.r, p.c, p.c + w - 1, '#');
  });
}

/**
 * ★ 无兜底地面 —— **明确挖空一段底层**，让玩家没法"掉下去再走回来"
 * ------------------------------------------------------------------
 * 【十一的要求】
 *   "遮棚下方不能一直有安全地面兜底" / "没有大面积安全地面的连续挑战段"
 *
 * ⚠️ 但**不能挖成深渊**（掉下去就死，会劝退）——
 *   所以这个函数只挖掉**主路那一层**，底下留一层"惩罚性地板"，
 *   掉下去要从下一段重来（配合检查点）。
 *
 * @param rows 要挖掉的行数（从 r 开始往下）
 */
function ch3NoFloor(g, r, c1, c2, rows) {
  const n = rows || 1;
  for (let k = 0; k < n; k++) hline(g, r + k, c1, c2, '.');
  /* 底下留一层"惩罚地板"（比主路低 3 行）——
   * 掉下去的玩家不会死，但要爬回来 = 失败有代价 */
  hline(g, r + n + 3, c1, c2, '#');
  /* ⚠️ 同样必须保住地图封底（见 ch3Chasm 的注释） */
  sealBottom(g, c1, c2);
}

