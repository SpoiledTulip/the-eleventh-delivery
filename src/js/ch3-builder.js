/** 一行尖刺 */
function ch3Spikes(g, r, c1, c2) { hline(g, r, c1, c2, '^'); }

/** 一段冰面（替换地面字符） */
function ch3Ice(g, r, c1, c2) {
  hline(g, r, c1, c2, 'I');
  hline(g, r + 1, c1, c2, '#');
}

/** 一段传送带 */
function ch3Conveyor(g, r, c1, c2, dir) {
  const ch = (dir === -1) ? '<' : '>';
  hline(g, r, c1, c2, ch);
  hline(g, r + 1, c1, c2, '#');
}

/** 一段断裂桥 */
function ch3Bridge(g, r, c1, c2) { hline(g, r, c1, c2, 'B'); }

/** 弹簧板 */
function ch3Spring(g, r, c) { put(g, r, c, 'S'); }

/** 移动平台（横向） */
function ch3Mover(g, r, c) { put(g, r, c, 'm'); }

/** 风场（向上） */
function ch3Wind(g, c, r1, r2) { vline(g, c, r1, r2, 'w'); }

/** 存档点 */
function ch3Checkpoint(g, r, c) { put(g, r, c, 'A'); }

/** 巡逻怪 */
function ch3Walker(g, r, c) { put(g, r, c, 'M'); }

/** 跳跳怪 */
function ch3Hopper(g, r, c) { put(g, r, c, 'j'); }

/** 开关 + 开关门（单人可用；⚠️ 绝不用 Y/O/D） */
function ch3Switch(g, r, c) { put(g, r, c, 't'); }
function ch3SwitchDoor(g, r, c) { put(g, r, c, 'h'); }

/** 出生点 */
function ch3Spawn(g, r, c) { put(g, r, c, 'P'); put(g, r, c + 1, 'N'); }

/** 终点 */
function ch3Goal(g, r, c) { put(g, r, c, 'G'); }

/* ============================================================
 * 像素 ↔ 格：把"设计上的格数"换算成机制需要的 px
 * ============================================================
 * CH3 机制（水柱/货柜/漏电区…）用的是**像素坐标**，
 * 而关卡设计用的是**格**。这两个来回换很容易错，
 * 所以统一用这组函数，别手算。
 * ============================================================ */
const CH3_T = 32;
function ch3Px(tiles) { return tiles * CH3_T; }
/** 格坐标 → 像素矩形（左上角） */
function ch3Box(r, c, wTiles, hTiles) {
  return { x: c * CH3_T, y: r * CH3_T, w: wTiles * CH3_T, h: hTiles * CH3_T };
}
